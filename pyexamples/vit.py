import sys

sys.path.append('../')
from pycore.tikzeng import *

# Vision Transformer (ViT) main pipeline
arch = [
    to_head('..'),
    to_cor(),
    to_begin(),
    to_Conv(
        "img",
        224,
        3,
        offset="(0,0,0)",
        to="(0,0,0)",
        height=36,
        depth=36,
        width=2,
        caption="Input image",
    ),
    to_Conv(
        "patchify",
        196,
        256,
        offset="(2,0,0)",
        to="(img-east)",
        width=3,
        height=26,
        depth=26,
        caption="Patchify (P×P)",
    ),
    to_connection("img", "patchify"),
    to_Conv(
        "flatten",
        196,
        256,
        offset="(1.25,0,0)",
        to="(patchify-east)",
        width=2.5,
        height=22,
        depth=22,
        caption="Flatten patches",
    ),
    to_connection("patchify", "flatten"),
    to_Conv(
        "proj",
        196,
        768,
        offset="(1.25,0,0)",
        to="(flatten-east)",
        width=5,
        height=22,
        depth=22,
        caption="Linear projection (FC)",
    ),
    to_connection("flatten", "proj"),
    to_Conv(
        "token_mix",
        197,
        768,
        offset="(1.5,0,0)",
        to="(proj-east)",
        width=4,
        height=22,
        depth=22,
        caption="Add [CLS] + position",
    ),
    to_connection("proj", "token_mix"),
    to_Conv(
        "ln1",
        "",
        "",
        offset="(1.25,0,0)",
        to="(token_mix-east)",
        width=1.5,
        height=20,
        depth=20,
        caption="LayerNorm",
    ),
    to_connection("token_mix", "ln1"),
    to_Conv(
        "mha",
        197,
        768,
        offset="(1.25,0,0)",
        to="(ln1-east)",
        width=6,
        height=26,
        depth=26,
        caption="Multi-Head Self-Attn",
    ),
    to_connection("ln1", "mha"),
    to_Conv(
        "res1",
        197,
        768,
        offset="(0.75,0,0)",
        to="(mha-east)",
        width=2,
        height=22,
        depth=22,
        caption="Residual add",
    ),
    to_connection("mha", "res1"),
    to_skip("token_mix", "res1", pos=1.1),
    to_Conv(
        "ln2",
        "",
        "",
        offset="(0.75,0,0)",
        to="(res1-east)",
        width=1.5,
        height=20,
        depth=20,
        caption="LayerNorm",
    ),
    to_connection("res1", "ln2"),
    to_Conv(
        "mlp",
        197,
        3072,
        offset="(1.25,0,0)",
        to="(ln2-east)",
        width=6,
        height=26,
        depth=26,
        caption="MLP (2-layer)",
    ),
    to_connection("ln2", "mlp"),
    to_Conv(
        "res2",
        197,
        768,
        offset="(0.75,0,0)",
        to="(mlp-east)",
        width=2,
        height=22,
        depth=22,
        caption="Residual add",
    ),
    to_connection("mlp", "res2"),
    to_skip("res1", "res2", pos=1.1),
    to_Conv(
        "encoder",
        "×L",
        768,
        offset="(1.75,0,0)",
        to="(res2-east)",
        width=10,
        height=30,
        depth=30,
        caption="Repeat L blocks",
    ),
    to_connection("res2", "encoder"),
    to_Conv(
        "cls_out",
        "",
        "",
        offset="(2,0,0)",
        to="(encoder-east)",
        width=2,
        height=18,
        depth=18,
        caption="[CLS] representation",
    ),
    to_connection("encoder", "cls_out"),
    to_SoftMax(
        "mlp_head",
        "Classes",
        offset="(1.5,0,0)",
        to="(cls_out-east)",
        width=2,
        height=10,
        depth=18,
        caption="MLP head",
    ),
    to_connection("cls_out", "mlp_head"),
    to_end(),
]


def main():
    namefile = str(sys.argv[0]).split(".")[0]
    to_generate(arch, namefile + ".tex")


if __name__ == "__main__":
    main()
